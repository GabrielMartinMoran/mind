// Skill installation for the mind-management skill.
//
// The canonical skill lives once at `~/.agents/skills/mind-management`.
// Clients that already discover `~/.agents` use it directly. Clients with a
// dedicated skills directory receive a symlink to the canonical directory
// (with a managed copy fallback) so the normative content never diverges.
//
// Policy: only the exact `mind-management` skill in an explicit Mind-managed
// location is updateable. The ownership marker is provenance, not
// authorization (old copies without it are backed up and updated). Other
// skills are never touched. Filesystem classification uses `lstat` so a
// symlink is replaced rather than followed and broken links are repairable.
import * as fs from 'node:fs';
import { homedir } from 'node:os';
import * as path from 'node:path';

import { renderMindManagementSkill } from '../cli/mind-management-skill';

import { atomicWriteText } from './safe-config';

// Supported agent types that can have skills installed.
export type AgentSkillType =
  | 'opencode'
  | 'claude-code'
  | 'cursor'
  | 'codex'
  | 'gemini-cli'
  | 'vscode'
  | 'windsurf'
  | 'antigravity'
  | 'pi';

export const SKILL_DIRNAME = 'mind-management';
export const SKILL_FILENAME = 'SKILL.md';
export const SKILL_OWNERSHIP_MARKER =
  '<!-- mind-managed-skill: generated by mind setup; do not edit -->';

export type SkillInstallStrategy = 'shared' | 'link';

export interface AgentSkillLayout {
  /** Real canonical directory shared by every client. */
  canonicalDir: string;
  /** Directory the client actually reads (canonical or a dedicated mirror). */
  targetDir: string;
  /** Legacy or higher-precedence directories that could shadow the canonical skill. */
  shadowDirs: string[];
  strategy: SkillInstallStrategy;
}

export interface SkillInstallOptions {
  /** Receives actionable warnings (repairs, symlink fallbacks). */
  warn?: (message: string) => void;
  /** Test seam for simulating symlink failures. Defaults to `fs.symlinkSync`. */
  symlinkSync?: typeof fs.symlinkSync;
}

export interface SkillInstallationResult {
  path: string | null;
  warnings: string[];
}

function getHomeDir(): string {
  return process.env.HOME ?? homedir();
}

export function getCanonicalSkillDir(home = getHomeDir()): string {
  return path.join(home, '.agents', 'skills', SKILL_DIRNAME);
}

export function getAgentSkillLayout(agent: AgentSkillType): AgentSkillLayout {
  const home = getHomeDir();
  const canonicalDir = getCanonicalSkillDir(home);

  switch (agent) {
    case 'opencode':
      return {
        canonicalDir,
        targetDir: canonicalDir,
        shadowDirs: [path.join(home, '.config', 'opencode', 'skills', SKILL_DIRNAME)],
        strategy: 'shared',
      };
    case 'claude-code':
      return {
        canonicalDir,
        targetDir: path.join(home, '.claude', 'skills', SKILL_DIRNAME),
        shadowDirs: [],
        strategy: 'link',
      };
    case 'cursor':
      return {
        canonicalDir,
        targetDir: canonicalDir,
        shadowDirs: [path.join(home, '.cursor', 'skills', SKILL_DIRNAME)],
        strategy: 'shared',
      };
    case 'codex':
      return { canonicalDir, targetDir: canonicalDir, shadowDirs: [], strategy: 'shared' };
    case 'windsurf':
      return {
        canonicalDir,
        targetDir: canonicalDir,
        shadowDirs: [
          path.join(home, '.config', 'devin', 'skills', SKILL_DIRNAME),
          // Legacy path retained for migration only; setup never writes it.
          path.join(home, '.windsurf', 'skills', SKILL_DIRNAME),
        ],
        strategy: 'shared',
      };
    case 'vscode':
      return {
        canonicalDir,
        targetDir: canonicalDir,
        shadowDirs: [path.join(home, '.copilot', 'skills', SKILL_DIRNAME)],
        strategy: 'shared',
      };
    case 'pi':
      return {
        canonicalDir,
        targetDir: canonicalDir,
        shadowDirs: [path.join(home, '.pi', 'agent', 'skills', SKILL_DIRNAME)],
        strategy: 'shared',
      };
    case 'gemini-cli':
      return {
        canonicalDir,
        targetDir: canonicalDir,
        shadowDirs: [path.join(home, '.gemini', 'skills', SKILL_DIRNAME)],
        strategy: 'shared',
      };
    case 'antigravity':
      return {
        canonicalDir,
        targetDir: path.join(home, '.gemini', 'config', 'skills', SKILL_DIRNAME),
        shadowDirs: [path.join(home, '.gemini', 'antigravity', 'skills', SKILL_DIRNAME)],
        strategy: 'link',
      };
  }
}

/** Path of the SKILL.md the client resolves after installation. */
export function getAgentSkillPath(agent: AgentSkillType): string {
  return path.join(getAgentSkillLayout(agent).targetDir, SKILL_FILENAME);
}

/**
 * All paths that prove the mind-management skill was installed for an agent:
 * the canonical copy, the client target, and any migratable legacy shadow.
 */
export function getAgentSkillSignalPaths(agent: AgentSkillType): string[] {
  const layout = getAgentSkillLayout(agent);
  const dirs = [layout.canonicalDir, layout.targetDir, ...layout.shadowDirs];
  return [...new Set(dirs.map(dir => path.join(dir, SKILL_FILENAME)))];
}

// Source path for the bundled mind-management skill template.
export function getSkillSourcePath(): string {
  return path.resolve(__dirname, '..', 'resources', 'skill-mind-management.md');
}

/** True when a path exists according to `lstat` (broken symlinks count). */
export function pathExistsLstat(filePath: string): boolean {
  return lstatOrNull(filePath) !== null;
}

/** Directory symlink type for a platform; a pure seam for Windows junction checks. */
export function resolveSymlinkType(
  platform: NodeJS.Platform = process.platform
): 'junction' | 'dir' {
  return platform === 'win32' ? 'junction' : 'dir';
}

/**
 * Ensure the single canonical skill exists. A no-op when the bytes already
 * match (no backup, no rewrite). Any same-name content in the managed
 * canonical location is backed up and replaced.
 */
export function ensureCanonicalSkill(
  rendered = renderMindManagementSkill()
): SkillInstallationResult {
  const canonicalDir = getCanonicalSkillDir();
  const warnings = prepareManagedDirectory(canonicalDir);
  warnings.push(...writeManagedSkillFile(canonicalDir, rendered));

  const dest = path.join(canonicalDir, SKILL_FILENAME);
  return {
    path: verifyInstalled(canonicalDir, rendered) ? dest : null,
    warnings,
  };
}

export function installMindManagementSkill(
  agent: AgentSkillType,
  options: SkillInstallOptions = {}
): SkillInstallationResult {
  if (!fs.existsSync(getSkillSourcePath())) {
    return { path: null, warnings: [] };
  }

  const rendered = renderMindManagementSkill();
  const canonical = ensureCanonicalSkill(rendered);
  if (canonical.path === null) {
    return { path: null, warnings: canonical.warnings };
  }

  const layout = getAgentSkillLayout(agent);
  const warnings = [...canonical.warnings];

  for (const shadowDir of layout.shadowDirs) {
    warnings.push(...pruneLegacyShadow(shadowDir, layout.canonicalDir));
  }

  if (layout.targetDir === layout.canonicalDir) {
    return { path: path.join(layout.canonicalDir, SKILL_FILENAME), warnings };
  }

  if (layout.strategy === 'link') {
    warnings.push(
      ...ensureLinkedSkill(
        layout.targetDir,
        layout.canonicalDir,
        rendered,
        options.symlinkSync ?? fs.symlinkSync
      )
    );
  } else {
    warnings.push(...ensureManagedSkillFile(layout.targetDir, rendered));
  }

  const targetSkillPath = path.join(layout.targetDir, SKILL_FILENAME);
  return {
    path: verifyInstalled(layout.targetDir, rendered) ? targetSkillPath : null,
    warnings,
  };
}

/**
 * Ensure the mind-management skill is installed for a given agent.
 * Returns the resolved SKILL.md path, or null when the skill cannot be
 * verified after installation.
 */
export function ensureMindManagementSkill(
  agent: AgentSkillType,
  options: SkillInstallOptions = {}
): string | null {
  const result = installMindManagementSkill(agent, options);
  const warn = options.warn ?? console.warn;
  for (const warning of result.warnings) {
    warn(warning);
  }
  return result.path;
}

// ---------------------------------------------------------------------------
// Managed-file helpers
// ---------------------------------------------------------------------------

/**
 * Ensure `targetDir` is a real directory. A symlink or a non-directory at a
 * managed path is backed up (recording a link target for symlinks) and
 * repaired instead of writing through it or throwing ENOTDIR.
 */
function prepareManagedDirectory(targetDir: string): string[] {
  const warnings: string[] = [];
  const stat = lstatOrNull(targetDir);

  if (stat === null) {
    ensureDirectory(targetDir);
    return warnings;
  }

  if (stat.isSymbolicLink()) {
    backupManagedSkill(targetDir);
    fs.unlinkSync(targetDir);
    ensureDirectory(targetDir);
    warnings.push(`Repaired symlink at ${targetDir}; the old link target was backed up.`);
    return warnings;
  }

  if (!stat.isDirectory()) {
    backupManagedSkill(targetDir);
    fs.rmSync(targetDir, { recursive: true, force: true });
    ensureDirectory(targetDir);
    warnings.push(`Repaired non-directory path at ${targetDir}; the old path was backed up.`);
    return warnings;
  }

  return warnings;
}

/**
 * Write the rendered SKILL.md into an existing managed directory. A symlink at
 * the file path is recorded and replaced, never followed.
 */
function writeManagedSkillFile(targetDir: string, rendered: string): string[] {
  const warnings = prepareManagedDirectory(targetDir);
  const dest = path.join(targetDir, SKILL_FILENAME);
  const stat = lstatOrNull(dest);

  if (stat === null) {
    atomicWriteText(dest, rendered);
    return warnings;
  }

  if (stat.isSymbolicLink()) {
    backupManagedSkill(dest);
    fs.unlinkSync(dest);
    atomicWriteText(dest, rendered);
    return warnings;
  }

  if (stat.isDirectory()) {
    const backupPath = uniquePath(`${dest}.bak.${backupTimestamp()}`);
    fs.renameSync(dest, backupPath);
    atomicWriteText(dest, rendered);
    warnings.push(`Repaired directory at ${dest}; it was moved to ${backupPath}.`);
    return warnings;
  }

  if (readFileOrNull(dest) === rendered) {
    return warnings;
  }

  backupManagedSkill(dest);
  atomicWriteText(dest, rendered);
  return warnings;
}

/** Copy strategy (or symlink fallback): a real directory with a managed file. */
function ensureManagedSkillFile(targetDir: string, rendered: string): string[] {
  return writeManagedSkillFile(targetDir, rendered);
}

/**
 * Link strategy: point the dedicated directory at the canonical skill. A
 * foreign or broken directory symlink is recorded and replaced; when linking
 * is unavailable or extras must be preserved, fall back to a managed copy.
 */
function ensureLinkedSkill(
  targetDir: string,
  canonicalDir: string,
  rendered: string,
  symlinkSync: typeof fs.symlinkSync
): string[] {
  const warnings: string[] = [];
  const stat = lstatOrNull(targetDir);

  if (stat === null) {
    ensureDirectory(path.dirname(targetDir));
    if (tryCreateDirectorySymlink(canonicalDir, targetDir, symlinkSync)) {
      return warnings;
    }
    warnings.push(
      `Could not link ${targetDir} to the canonical skill; using a managed copy instead.`
    );
    warnings.push(...ensureManagedSkillFile(targetDir, rendered));
    return warnings;
  }

  if (stat.isSymbolicLink()) {
    if (resolvesTo(targetDir, canonicalDir)) {
      return warnings;
    }
    backupManagedSkill(targetDir);
    fs.unlinkSync(targetDir);
    if (tryCreateDirectorySymlink(canonicalDir, targetDir, symlinkSync)) {
      return warnings;
    }
    warnings.push(
      `Could not link ${targetDir} to the canonical skill; using a managed copy instead.`
    );
    warnings.push(...ensureManagedSkillFile(targetDir, rendered));
    return warnings;
  }

  if (!stat.isDirectory()) {
    warnings.push(...prepareManagedDirectory(targetDir));
  }

  const dest = path.join(targetDir, SKILL_FILENAME);
  const destStat = lstatOrNull(dest);

  if (destStat !== null && destStat.isFile() && readFileOrNull(dest) === rendered) {
    // A previous copy fallback is already current; keep it stable.
    return warnings;
  }

  const extras = listMeaningfulEntries(targetDir);

  if (extras.length === 0) {
    if (destStat !== null) {
      backupManagedSkill(targetDir);
    }
    fs.rmSync(targetDir, { recursive: true, force: true });
    if (tryCreateDirectorySymlink(canonicalDir, targetDir, symlinkSync)) {
      return warnings;
    }
    warnings.push(
      `Could not link ${targetDir} to the canonical skill; using a managed copy instead.`
    );
    warnings.push(...ensureManagedSkillFile(targetDir, rendered));
    return warnings;
  }

  // Preserve unrelated resources; refresh only the managed SKILL.md.
  warnings.push(...writeManagedSkillFile(targetDir, rendered));
  return warnings;
}

/**
 * Remove a legacy shadow copy that would take precedence over the canonical
 * skill. The same-name skill in a managed legacy location is backed up before
 * pruning; unrelated resources in the directory are preserved.
 */
function pruneLegacyShadow(shadowDir: string, canonicalDir: string): string[] {
  const stat = lstatOrNull(shadowDir);
  if (stat === null) {
    return [];
  }

  if (stat.isSymbolicLink()) {
    if (resolvesTo(shadowDir, canonicalDir)) {
      return [];
    }
    backupManagedSkill(shadowDir);
    fs.unlinkSync(shadowDir);
    return [`Replaced legacy shadow symlink at ${shadowDir}; its target was backed up.`];
  }

  if (!stat.isDirectory()) {
    backupManagedSkill(shadowDir);
    fs.rmSync(shadowDir, { recursive: true, force: true });
    return [`Removed legacy shadow path at ${shadowDir}; it was backed up.`];
  }

  const dest = path.join(shadowDir, SKILL_FILENAME);
  const destStat = lstatOrNull(dest);
  if (destStat === null) {
    return [];
  }

  const extras = listMeaningfulEntries(shadowDir);
  backupManagedSkill(shadowDir);

  if (extras.length === 0) {
    fs.rmSync(shadowDir, { recursive: true, force: true });
  } else if (destStat.isSymbolicLink()) {
    fs.unlinkSync(dest);
  } else {
    fs.rmSync(dest, { recursive: true, force: true });
  }

  return [];
}

function tryCreateDirectorySymlink(
  canonicalDir: string,
  targetDir: string,
  symlinkSync: typeof fs.symlinkSync
): boolean {
  try {
    symlinkSync(canonicalDir, targetDir, resolveSymlinkType());
    return true;
  } catch {
    return false;
  }
}

function verifyInstalled(targetDir: string, rendered: string): boolean {
  const dirStat = lstatOrNull(targetDir);
  if (dirStat === null) {
    return false;
  }
  if (dirStat.isSymbolicLink() && !resolvesTo(targetDir, getCanonicalSkillDir())) {
    return false;
  }
  if (!dirStat.isSymbolicLink() && !dirStat.isDirectory()) {
    return false;
  }

  const dest = path.join(targetDir, SKILL_FILENAME);
  const destStat = lstatOrNull(dest);
  if (destStat === null || destStat.isSymbolicLink() || !destStat.isFile()) {
    return false;
  }
  return readFileOrNull(dest) === rendered;
}

// ---------------------------------------------------------------------------
// Backups and filesystem primitives
// ---------------------------------------------------------------------------

/**
 * Back up a managed path before replacing it.
 *
 * - Regular file: timestamped sibling copy (`.bak.<timestamp>`).
 * - Symlink: sibling sidecar recording `LINK_TARGET=<target>`; never copies
 *   external bytes.
 * - Directory: sibling directory containing only `SKILL.md` (or a LINK_TARGET
 *   sidecar when that file is a symlink); unrelated resources stay in place.
 */
function backupManagedSkill(targetPath: string): string | null {
  const stat = lstatOrNull(targetPath);
  if (stat === null) {
    return null;
  }

  const backupPath = uniquePath(`${targetPath}.bak.${backupTimestamp()}`);

  if (stat.isSymbolicLink()) {
    fs.writeFileSync(backupPath, `LINK_TARGET=${fs.readlinkSync(targetPath)}\n`);
    return backupPath;
  }

  if (stat.isDirectory()) {
    const skillPath = path.join(targetPath, SKILL_FILENAME);
    const skillStat = lstatOrNull(skillPath);
    if (skillStat === null) {
      return null;
    }
    fs.mkdirSync(backupPath, { recursive: true });
    if (skillStat.isSymbolicLink()) {
      fs.writeFileSync(
        path.join(backupPath, SKILL_FILENAME),
        `LINK_TARGET=${fs.readlinkSync(skillPath)}\n`
      );
    } else if (skillStat.isFile()) {
      fs.copyFileSync(skillPath, path.join(backupPath, SKILL_FILENAME));
    } else {
      fs.rmSync(backupPath, { recursive: true, force: true });
      return null;
    }
    return backupPath;
  }

  fs.copyFileSync(targetPath, backupPath);
  return backupPath;
}

function uniquePath(candidate: string): string {
  if (lstatOrNull(candidate) === null) {
    return candidate;
  }
  for (let index = 1; index < 1000; index += 1) {
    const next = `${candidate}-${index}`;
    if (lstatOrNull(next) === null) {
      return next;
    }
  }
  throw new Error(`Could not allocate a unique backup path for ${candidate}`);
}

function backupTimestamp(): string {
  return new Date()
    .toISOString()
    .replace(/[-:]/g, '')
    .replace(/\.(\d{3})Z$/, '$1Z');
}

function resolvesTo(candidate: string, target: string): boolean {
  try {
    return fs.realpathSync(candidate) === fs.realpathSync(target);
  } catch {
    return false;
  }
}

function lstatOrNull(filePath: string): fs.Stats | null {
  try {
    return fs.lstatSync(filePath);
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code;
    // ENOTDIR means an ancestor is not a directory. Treat it like a missing
    // path so `ensureDirectory` can back up and repair the blocking ancestor.
    if (code === 'ENOENT' || code === 'ENOTDIR') {
      return null;
    }
    throw err;
  }
}

function readFileOrNull(filePath: string): string | null {
  try {
    return fs.readFileSync(filePath, 'utf-8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') {
      return null;
    }
    throw err;
  }
}

function listMeaningfulEntries(dirPath: string): string[] {
  return fs
    .readdirSync(dirPath)
    .filter(name => name !== SKILL_FILENAME && !name.startsWith(`${SKILL_FILENAME}.bak.`));
}

/**
 * Create a directory, repairing a non-directory ancestor (for example a file
 * where one of the managed directories should be) instead of throwing
 * ENOTDIR.
 */
function ensureDirectory(dirPath: string): void {
  try {
    fs.mkdirSync(dirPath, { recursive: true });
    return;
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code;
    if (code !== 'ENOTDIR' && code !== 'EEXIST' && code !== 'ENOENT') {
      throw err;
    }
  }

  let candidate = dirPath;
  while (true) {
    const stat = lstatOrNull(candidate);
    if (stat !== null) {
      if (!stat.isDirectory()) {
        backupManagedSkill(candidate);
        fs.rmSync(candidate, { recursive: true, force: true });
      }
      break;
    }
    const parent = path.dirname(candidate);
    if (parent === candidate) {
      break;
    }
    candidate = parent;
  }

  fs.mkdirSync(dirPath, { recursive: true });
}
