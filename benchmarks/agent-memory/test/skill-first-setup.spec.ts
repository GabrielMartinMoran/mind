// Unit tests for the shared skill-first preparation.
//
// Every test uses temporary directories plus an injected fake command runner:
// no real HOME, no real database, no OpenCode and no paid model call.

import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

import { describe, expect, test } from 'bun:test';

import type { CommandInvocation } from '../src/exec';
import {
  buildOpenCodeEnv,
  ensureIsolationDirs,
  isolationDirs,
  type IsolationDirs,
} from '../src/isolation/opencode';
import {
  MIND_MANAGEMENT_SKILL,
  SKILL_FIRST_SKILLS,
  SkillFirstSetupError,
  applyActivationToEnv,
  briefActivationPath,
  canonicalSkillPath,
  prepareSkillFirst,
} from '../src/opencode/skill-first';
import { createFakeRunner } from '../src/testing/fakes';

const SKILL_CONTENT = [
  '---',
  'name: mind-management',
  'description: test fixture',
  '---',
  '',
  '<!-- mind-managed-skill: generated by mind setup; do not edit -->',
  '',
  'Skill body.',
  '',
].join('\n');

const ACTIVATION_CONTENT =
  'Load the mind-management skill at session start. If it cannot be loaded, call system_instructions.\n';

interface Harness {
  readonly root: string;
  readonly dir: IsolationDirs;
  readonly mindBin: string;
  readonly env: Record<string, string>;
}

function makeHarness(): Harness {
  const root = mkdtempSync(join(tmpdir(), 'bench-skill-first-'));
  const dir = isolationDirs(join(root, 'mind-current'));
  ensureIsolationDirs(dir);
  const mindBin = join(root, 'mind');
  const env = buildOpenCodeEnv({ condition: 'mind-current', dir, mindBin });
  return { root, dir, mindBin, env };
}

function writeFile(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
}

function writeSkill(home: string, content = SKILL_CONTENT): void {
  writeFile(canonicalSkillPath(home), content);
}

function writeActivation(path: string, content = ACTIVATION_CONTENT): void {
  writeFile(path, content);
}

function xdgActivationPath(dir: IsolationDirs): string {
  return join(dir.config, 'opencode', 'instructions', 'mind-memory-protocol.md');
}

/** Fake `mind setup opencode` that writes the real artifacts under the child HOME. */
function setupRunner(options: {
  readonly skillContent?: string;
  readonly activationContent?: string;
  readonly writeXdgActivation?: boolean;
  readonly exitCode?: number;
  readonly stderr?: string;
}): ReturnType<typeof createFakeRunner> {
  return createFakeRunner((invocation: CommandInvocation) => {
    const home = invocation.env?.HOME;
    if (home && options.exitCode === undefined) {
      writeSkill(home, options.skillContent);
      writeActivation(briefActivationPath(home), options.activationContent);
      if (options.writeXdgActivation) {
        const xdgConfig = invocation.env?.XDG_CONFIG_HOME;
        if (xdgConfig) {
          writeActivation(
            join(xdgConfig, 'opencode', 'instructions', 'mind-memory-protocol.md'),
            options.activationContent
          );
        }
      }
    }
    return { exitCode: options.exitCode, stderr: options.stderr };
  });
}

async function expectError(
  promise: Promise<unknown>,
  code: SkillFirstSetupError['code']
): Promise<SkillFirstSetupError> {
  try {
    await promise;
  } catch (error) {
    expect(error).toBeInstanceOf(SkillFirstSetupError);
    const typed = error as SkillFirstSetupError;
    expect(typed.code).toBe(code);
    return typed;
  }
  throw new Error(`expected rejection with code '${code}'`);
}

describe('path helpers and constants', () => {
  test('exposes the canonical skill and brief activation paths', () => {
    expect(canonicalSkillPath('/isolated/home')).toBe(
      '/isolated/home/.agents/skills/mind-management/SKILL.md'
    );
    expect(briefActivationPath('/isolated/home')).toBe(
      '/isolated/home/.config/opencode/instructions/mind-memory-protocol.md'
    );
  });

  test('freezes the exact skill-first allowlist', () => {
    expect(SKILL_FIRST_SKILLS).toEqual(['opencode', 'report', MIND_MANAGEMENT_SKILL]);
    expect(Object.isFrozen(SKILL_FIRST_SKILLS)).toBe(true);
  });
});

describe('applyActivationToEnv', () => {
  test('prepends the activation path and preserves unrelated config keys', () => {
    const env = {
      OTHER: 'value',
      OPENCODE_CONFIG_CONTENT: JSON.stringify({
        model: 'openrouter/x',
        instructions: ['/existing.md'],
      }),
    };

    const prepared = applyActivationToEnv(env, '/isolated/l2.md');
    const parsed = JSON.parse(prepared.OPENCODE_CONFIG_CONTENT!) as {
      model: string;
      instructions: string[];
    };

    expect(parsed.model).toBe('openrouter/x');
    expect(parsed.instructions).toEqual(['/isolated/l2.md', '/existing.md']);
    expect(prepared.OTHER).toBe('value');
    expect(prepared).not.toBe(env);
  });

  test('is idempotent and deduplicates repeated entries', () => {
    const env = {
      OPENCODE_CONFIG_CONTENT: JSON.stringify({
        instructions: ['/duplicate.md', '/duplicate.md'],
      }),
    };

    const once = applyActivationToEnv(env, '/isolated/l2.md');
    const twice = applyActivationToEnv(once, '/isolated/l2.md');
    const parsed = JSON.parse(twice.OPENCODE_CONFIG_CONTENT!) as { instructions: string[] };

    expect(parsed.instructions).toEqual(['/isolated/l2.md', '/duplicate.md']);
  });

  test('fails closed on missing or malformed inline config', () => {
    expect(() => applyActivationToEnv({}, '/isolated/l2.md')).toThrow(SkillFirstSetupError);
    expect(() =>
      applyActivationToEnv({ OPENCODE_CONFIG_CONTENT: '{not-json' }, '/isolated/l2.md')
    ).toThrow(SkillFirstSetupError);
  });
});

describe('prepareSkillFirst', () => {
  test('runs the real setup command with an explicitly minimal isolated env', async () => {
    const { dir, mindBin, env } = makeHarness();
    const fake = setupRunner({});

    const prepared = await prepareSkillFirst({ dir, env, mindBin, run: fake.runner });

    expect(fake.calls).toHaveLength(1);
    const call = fake.calls[0]!;
    expect(call.command).toBe(mindBin);
    expect(call.args).toEqual(['setup', 'opencode']);
    expect(call.cwd).toBe(dir.workspace);
    expect(call.timeoutMs).toBe(120_000);

    expect(call.env).toBeDefined();
    const childEnv = call.env as Record<string, string>;
    expect(childEnv.HOME).toBe(dir.home);
    expect(childEnv.XDG_CONFIG_HOME).toBe(dir.config);
    expect(childEnv.XDG_DATA_HOME).toBe(dir.data);
    expect(childEnv.XDG_STATE_HOME).toBe(dir.state);
    expect(childEnv.XDG_CACHE_HOME).toBe(dir.cache);
    expect(childEnv.MIND_DB_PATH).toBe(dir.mindDb);
    expect(childEnv.MIND_DATA_DIR).toBe(dir.mindDataDir);
    expect(childEnv.MIND_SYNC_ROOT).toBe(dir.syncRoot);
    expect(childEnv.MIND_RAG).toBe('false');
    expect(childEnv.PATH).toBe(process.env.PATH);

    // Nothing from the host env is spread implicitly.
    expect(Object.keys(childEnv).sort()).toEqual(
      [
        'HOME',
        'MIND_DB_PATH',
        'MIND_DATA_DIR',
        'MIND_RAG',
        'MIND_SYNC_ROOT',
        'PATH',
        'XDG_CACHE_HOME',
        'XDG_CONFIG_HOME',
        'XDG_DATA_HOME',
        'XDG_STATE_HOME',
      ].sort()
    );
    expect(childEnv.OPENCODE_CONFIG_CONTENT).toBeUndefined();
    expect(childEnv.OPENROUTER_API_KEY).toBeUndefined();

    expect(prepared.skillPath).toBe(canonicalSkillPath(dir.home));
    expect(prepared.activationPath).toBe(briefActivationPath(dir.home));
    const parsed = JSON.parse(prepared.env.OPENCODE_CONFIG_CONTENT!) as {
      instructions: string[];
    };
    expect(parsed.instructions).toEqual([briefActivationPath(dir.home)]);
  });

  test('honours an explicit timeout', async () => {
    const { dir, mindBin, env } = makeHarness();
    const fake = setupRunner({});

    await prepareSkillFirst({ dir, env, mindBin, run: fake.runner, timeoutMs: 5_000 });

    expect(fake.calls[0]!.timeoutMs).toBe(5_000);
  });

  test('fails with exit code and stderr tail when setup exits non-zero', async () => {
    const { dir, mindBin, env } = makeHarness();
    const fake = setupRunner({ exitCode: 1, stderr: 'setup exploded badly\n' });

    const error = await expectError(
      prepareSkillFirst({ dir, env, mindBin, run: fake.runner }),
      'setup-failed'
    );

    expect(error.message).toContain('exited 1');
    expect(error.stderrTail).toContain('setup exploded badly');
  });

  test('fails when setup exits 0 without writing the artifacts', async () => {
    const { dir, mindBin, env } = makeHarness();
    const fake = createFakeRunner();

    const error = await expectError(
      prepareSkillFirst({ dir, env, mindBin, run: fake.runner }),
      'missing-skill'
    );

    expect(error.message).toContain(canonicalSkillPath(dir.home));
  });

  test.each([
    [
      'foreign frontmatter name',
      '---\nname: other-skill\n---\n\n<!-- mind-managed-skill: generated by mind setup; do not edit -->\n',
    ],
    ['missing frontmatter', 'just a body\n'],
    ['missing ownership marker', '---\nname: mind-management\n---\n\nbody\n'],
  ])('rejects a skill with %s', async (_label, content) => {
    const { dir, mindBin, env } = makeHarness();
    const fake = setupRunner({ skillContent: content });

    const error = await expectError(
      prepareSkillFirst({ dir, env, mindBin, run: fake.runner }),
      'invalid-skill'
    );

    expect(error.message).toContain(canonicalSkillPath(dir.home));
  });

  test.each([
    ['missing mind-management', 'Call system_instructions when needed.\n'],
    ['missing system_instructions', 'Load the mind-management skill.\n'],
    ['full protocol body', 'mind-management system_instructions\n## ORIENT\nfull body\n'],
    ['oversized activation', `mind-management system_instructions\n${'x'.repeat(2_000)}`],
  ])('rejects activation with %s', async (_label, content) => {
    const { dir, mindBin, env } = makeHarness();
    const fake = setupRunner({ activationContent: content });

    const error = await expectError(
      prepareSkillFirst({ dir, env, mindBin, run: fake.runner }),
      'invalid-activation'
    );

    expect(error.message).toContain(briefActivationPath(dir.home));
  });

  test('fails closed when the activation exists under both HOME and XDG roots', async () => {
    const { dir, mindBin, env } = makeHarness();
    const fake = setupRunner({ writeXdgActivation: true });

    const error = await expectError(
      prepareSkillFirst({ dir, env, mindBin, run: fake.runner }),
      'ambiguous-activation'
    );

    expect(error.message).toContain(briefActivationPath(dir.home));
    expect(error.message).toContain(xdgActivationPath(dir));
  });

  test('accepts exactly one activation under the XDG config root', async () => {
    const { dir, mindBin, env } = makeHarness();
    const fake = createFakeRunner(invocation => {
      const home = invocation.env?.HOME;
      if (home) {
        writeSkill(home);
        writeActivation(xdgActivationPath(dir));
      }
      return {};
    });

    const prepared = await prepareSkillFirst({ dir, env, mindBin, run: fake.runner });

    expect(prepared.activationPath).toBe(xdgActivationPath(dir));
  });

  test('rejects a HOME outside the isolated condition directory', async () => {
    const { root, dir, mindBin, env } = makeHarness();
    const outside = mkdtempSync(join(tmpdir(), 'bench-skill-first-outside-'));
    const fake = setupRunner({});

    const error = await expectError(
      prepareSkillFirst({
        dir: { ...dir, home: outside },
        env,
        mindBin,
        run: fake.runner,
      }),
      'invalid-environment'
    );

    expect(fake.calls).toHaveLength(0);
    expect(error.message).toContain(outside);
    expect(root).not.toBe(outside);
  });

  test('rejects a HOME equal to the real process HOME', async () => {
    const { dir, mindBin, env } = makeHarness();
    const realHome = resolve(process.env.HOME ?? homedir());
    const conditionDir = dirname(realHome);
    const fake = setupRunner({});

    const error = await expectError(
      prepareSkillFirst({
        dir: {
          ...dir,
          conditionDir,
          home: realHome,
          config: join(conditionDir, 'cfg'),
          data: join(conditionDir, 'data'),
          state: join(conditionDir, 'state'),
          cache: join(conditionDir, 'cache'),
        },
        env,
        mindBin,
        run: fake.runner,
      }),
      'invalid-environment'
    );

    expect(fake.calls).toHaveLength(0);
    expect(error.message).toContain('real HOME');
  });

  test('rejects a missing mind binary before running setup', async () => {
    const { dir, env } = makeHarness();
    const fake = setupRunner({});

    const error = await expectError(
      prepareSkillFirst({ dir, env, mindBin: null, run: fake.runner }),
      'missing-mind-bin'
    );

    expect(fake.calls).toHaveLength(0);
    expect(error.message).toContain('mind');
  });
});
