import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { describe, expect, test } from 'bun:test';

import { BUILTIN_SKILLS } from '../src/config';
import type { CommandInvocation } from '../src/exec';
import { isolationDirs, type IsolationDirs } from '../src/isolation/opencode';
import { ContaminationError, verifyIsolation } from '../src/isolation/verify';
import {
  SKILL_FIRST_SKILLS,
  briefActivationPath,
  canonicalSkillPath,
} from '../src/opencode/skill-first';
import { createFakeRunner, type FakeCommandResolver } from '../src/testing/fakes';

const SKILL_CONTENT = [
  '---',
  'name: mind-management',
  'description: test fixture',
  '---',
  '',
  '<!-- mind-managed-skill: generated by mind setup; do not edit -->',
  '',
  'Skill body.',
  '',
].join('\n');

const ACTIVATION_CONTENT =
  'Load the mind-management skill at session start. If it cannot be loaded, call system_instructions.\n';

const conditionDir = mkdtempSync(join(tmpdir(), 'bench-verify-'));
const dir = isolationDirs(conditionDir);
const env = { HOME: dir.home, XDG_CONFIG_HOME: dir.config };

const noSleep = async (): Promise<void> => undefined;

interface CurrentHarness {
  readonly root: string;
  readonly dir: IsolationDirs;
  readonly mindBin: string;
  readonly env: Record<string, string>;
  readonly skillPath: string;
  readonly activationPath: string;
}

function makeCurrentHarness(options: { skill?: string; activation?: string } = {}): CurrentHarness {
  const root = mkdtempSync(join(tmpdir(), 'bench-verify-current-'));
  const currentDir = isolationDirs(join(root, 'mind-current'));
  const skillPath = canonicalSkillPath(currentDir.home);
  const activationPath = briefActivationPath(currentDir.home);
  if (options.skill !== undefined) writeFile(skillPath, options.skill);
  if (options.activation !== undefined) writeFile(activationPath, options.activation);
  return {
    root,
    dir: currentDir,
    mindBin: '/x/mind',
    env: {
      HOME: currentDir.home,
      XDG_CONFIG_HOME: currentDir.config,
      OPENCODE_CONFIG_CONTENT: JSON.stringify({ instructions: [activationPath] }),
    },
    skillPath,
    activationPath,
  };
}

function writeFile(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
}

interface Overrides {
  pathLeak?: boolean;
  extraMcp?: boolean;
  sessions?: string;
  skills?: string;
}

function goodResolver(target: IsolationDirs, overrides: Overrides = {}): FakeCommandResolver {
  const pathLines = (['home', 'data', 'cache', 'config', 'state'] as const)
    .map(k => `${k} ${target[k]}`)
    .join('\n');
  const leak = overrides.pathLeak ? `\nleak /home/user/.config/opencode` : '';
  const servers: Record<string, unknown> = { mind: { type: 'local', command: ['/x/mind', 'mcp'] } };
  if (overrides.extraMcp) servers['rogue'] = { type: 'local', command: ['/x/rogue', 'mcp'] };
  const skills = overrides.skills ?? JSON.stringify({ data: BUILTIN_SKILLS.map(id => ({ id })) });

  return (inv: CommandInvocation) => {
    const key = inv.args.join(' ');
    if (key === 'debug paths') return { stdout: `${pathLines}${leak}\n` };
    if (key === 'debug config') {
      return {
        stdout: JSON.stringify([
          {
            type: 'document',
            info: {
              $schema: 'https://opencode.ai/config.json',
              model: { providerID: 'openrouter', model: 'openai/gpt-6-luna' },
              mcp: { servers },
            },
          },
        ]),
      };
    }
    if (key === 'mcp list') return { stdout: 'mind  pending\n' };
    if (key === 'session list --format json') return { stdout: overrides.sessions ?? '[]' };
    if (key === 'api get /api/agent') return { stdout: '{"data":[]}' };
    if (key === 'api get /api/skill') return { stdout: skills };
    if (key === 'api get /api/command') return { stdout: '{"data":[]}' };
    if (key === 'api get /api/plugin') return { stdout: '{"data":[{"id":"opencode.tool.read"}]}' };
    return { stdout: '' };
  };
}

function cleanNoMemoryResolver(skills = '{"data":[]}'): FakeCommandResolver {
  return inv => {
    const key = inv.args.join(' ');
    if (key === 'debug paths') return { stdout: `home ${dir.home}\n` };
    if (key === 'debug config')
      return {
        stdout: JSON.stringify([
          {
            type: 'document',
            info: { model: { providerID: 'openrouter', model: 'openai/gpt-6-luna' } },
          },
        ]),
      };
    if (key === 'mcp list') return { stdout: 'No MCP servers configured\n' };
    if (key === 'session list --format json') return { stdout: '[]' };
    if (key === 'api get /api/skill') return { stdout: skills };
    return { stdout: '{"data":[]}' };
  };
}

async function verify(
  resolver: FakeCommandResolver,
  options: {
    condition?: 'mind-v9' | 'mind-v10' | 'mind-current' | 'no-memory';
    dir?: IsolationDirs;
    env?: Record<string, string>;
    mindBin?: string | null;
  } = {}
) {
  const evidenceDir = mkdtempSync(join(tmpdir(), 'bench-verify-evid-'));
  const fake = createFakeRunner(resolver);
  return verifyIsolation({
    condition: options.condition ?? 'mind-v10',
    dir: options.dir ?? dir,
    env: options.env ?? env,
    runner: fake.runner,
    evidenceDir,
    sleep: noSleep,
    ...(options.mindBin !== undefined ? { mindBin: options.mindBin } : {}),
  });
}

/** Override only `/api/skill` with a scripted sequence; everything else is clean. */
function sequencedSkillsResolver(
  target: IsolationDirs,
  responses: readonly string[]
): FakeCommandResolver {
  const base = goodResolver(target);
  let call = 0;
  return invocation => {
    if (invocation.args.join(' ') === 'api get /api/skill') {
      const stdout = responses[Math.min(call, responses.length - 1)]!;
      call += 1;
      return { stdout };
    }
    return base(invocation);
  };
}

function skillIds(ids: readonly string[]): string {
  return JSON.stringify({ data: ids.map(id => ({ id })) });
}

async function verifyCurrent(
  harness: CurrentHarness,
  resolver: FakeCommandResolver,
  mindBin: string | null = harness.mindBin
) {
  return verify(resolver, {
    condition: 'mind-current',
    dir: harness.dir,
    env: harness.env,
    mindBin,
  });
}

async function expectContamination(promise: Promise<unknown>, reason: string): Promise<void> {
  try {
    await promise;
  } catch (error) {
    expect(error).toBeInstanceOf(ContaminationError);
    expect((error as ContaminationError).reasons.join(' ')).toContain(reason);
    return;
  }
  throw new Error('expected isolation contamination');
}

describe('verifyIsolation', () => {
  test('passes for a clean mind condition and saves evidence', async () => {
    const report = await verify(goodResolver(dir));
    expect(report.ok).toBe(true);
    expect(report.condition).toBe('mind-v10');
    expect(existsSync(join(report.evidenceDir!, 'summary.txt'))).toBe(true);
    expect(existsSync(join(report.evidenceDir!, 'debug-config.stdout.txt'))).toBe(true);
  });

  test('passes for a clean no-memory condition', async () => {
    const report = await verify(cleanNoMemoryResolver(), { condition: 'no-memory' });
    expect(report.ok).toBe(true);
  });

  test('passes for a current condition with the exact skill surface', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    const report = await verifyCurrent(
      harness,
      goodResolver(harness.dir, {
        skills: '{"data":[{"id":"opencode"},{"id":"report"},{"id":"mind-management"}]}',
      })
    );
    expect(report.ok).toBe(true);
    const skillFirst = report.checks.find(check => check.name === 'skill-first');
    expect(skillFirst?.ok).toBe(true);
    const skillsCheck = report.checks.find(check => check.name === 'skills-allowlisted');
    expect(skillsCheck?.ok).toBe(true);
    expect(report.checks).toHaveLength(9);
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails when discovery omits mind-management', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    await expectContamination(
      verifyCurrent(harness, goodResolver(harness.dir)),
      'discovered skills'
    );
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails closed when the activation path is a directory', async () => {
    const harness = makeCurrentHarness({ skill: SKILL_CONTENT });
    mkdirSync(harness.activationPath, { recursive: true });
    await expectContamination(
      verifyCurrent(harness, goodResolver(harness.dir)),
      'not a regular file'
    );
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails closed on a path leak and writes dumps', async () => {
    const promise = verify(goodResolver(dir, { pathLeak: true }));
    await expect(promise).rejects.toThrow(ContaminationError);
    try {
      await promise;
    } catch (error) {
      const contamination = error as ContaminationError;
      expect(contamination.reasons.some(r => r.includes('paths-under-condition-dir'))).toBe(true);
      expect(existsSync(join(contamination.report.evidenceDir!, 'debug-paths.stdout.txt'))).toBe(
        true
      );
    }
  });

  test('fails when an unauthorized MCP server is present', async () => {
    await expectContamination(verify(goodResolver(dir, { extraMcp: true })), 'MCP');
  });

  test('fails when sessions leak', async () => {
    await expectContamination(verify(goodResolver(dir, { sessions: '[{"id":"ses_user"}]' })), '');
  });

  test('fails when a user skill leaks', async () => {
    await expectContamination(
      verify(goodResolver(dir, { skills: '{"data":[{"id":"opencode"},{"id":"user-private"}]}' })),
      'skills'
    );
  });

  test('proves mind-current runs the expected local checkout binary', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    const report = await verifyCurrent(
      harness,
      goodResolver(harness.dir, {
        skills: '{"data":[{"id":"opencode"},{"id":"report"},{"id":"mind-management"}]}',
      })
    );
    expect(report.ok).toBe(true);
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails closed when mind-current is wired to a different binary', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    await expectContamination(
      verifyCurrent(harness, goodResolver(harness.dir), '/somewhere/else/mind'),
      'mind'
    );
    rmSync(harness.root, { recursive: true, force: true });
  });
});

describe('skill discovery warm-up', () => {
  function coldStartHarness(): CurrentHarness {
    return makeCurrentHarness({ skill: SKILL_CONTENT, activation: ACTIVATION_CONTENT });
  }

  test('retries the skill listing until the exact surface appears', async () => {
    const harness = coldStartHarness();
    const responses = [skillIds(BUILTIN_SKILLS), skillIds(SKILL_FIRST_SKILLS)];
    const evidenceDir = mkdtempSync(join(tmpdir(), 'bench-verify-evid-'));
    const fake = createFakeRunner(sequencedSkillsResolver(harness.dir, responses));

    const report = await verifyIsolation({
      condition: 'mind-current',
      dir: harness.dir,
      env: harness.env,
      runner: fake.runner,
      evidenceDir,
      mindBin: harness.mindBin,
      sleep: noSleep,
    });

    expect(report.ok).toBe(true);
    expect(report.checks).toHaveLength(9);
    expect(report.checks.find(check => check.name === 'skills-allowlisted')?.ok).toBe(true);
    expect(report.checks.find(check => check.name === 'skill-first')?.ok).toBe(true);
    expect(fake.calls.filter(inv => inv.args.join(' ') === 'api get /api/skill')).toHaveLength(2);
    // The final (successful) listing is the one saved as evidence.
    const evidence = readFileSync(join(evidenceDir, 'api-skill.stdout.txt'), 'utf8');
    expect(evidence).toContain('mind-management');

    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails closed with the missing skill after the retry budget', async () => {
    const harness = coldStartHarness();
    // Every response omits the installed skill, so the budget is exhausted.
    const fake = createFakeRunner(sequencedSkillsResolver(harness.dir, [skillIds(BUILTIN_SKILLS)]));
    const evidenceDir = mkdtempSync(join(tmpdir(), 'bench-verify-evid-'));

    try {
      await verifyIsolation({
        condition: 'mind-current',
        dir: harness.dir,
        env: harness.env,
        runner: fake.runner,
        evidenceDir,
        mindBin: harness.mindBin,
        sleep: noSleep,
        skillListAttempts: 3,
      });
      throw new Error('expected isolation contamination');
    } catch (error) {
      expect(error).toBeInstanceOf(ContaminationError);
      expect((error as ContaminationError).reasons.join(' ')).toContain(
        'missing [mind-management]'
      );
      expect(fake.calls.filter(inv => inv.args.join(' ') === 'api get /api/skill')).toHaveLength(3);
      // The failed final snapshot stays visible as evidence.
      const evidence = readFileSync(join(evidenceDir, 'api-skill.stdout.txt'), 'utf8');
      expect(evidence).not.toContain('mind-management');
    }

    rmSync(harness.root, { recursive: true, force: true });
  });
});

describe('condition-derived skill-first check', () => {
  test('fails when the current canonical skill is missing', async () => {
    const harness = makeCurrentHarness({ activation: ACTIVATION_CONTENT });
    await expectContamination(verifyCurrent(harness, goodResolver(harness.dir)), 'skill');
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails when the current brief activation is missing', async () => {
    const harness = makeCurrentHarness({ skill: SKILL_CONTENT });
    await expectContamination(verifyCurrent(harness, goodResolver(harness.dir)), 'activation');
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails when mind-current has no mind binary', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    await expectContamination(verifyCurrent(harness, goodResolver(harness.dir), null), 'mind');
    rmSync(harness.root, { recursive: true, force: true });
  });

  test.each([
    ['malformed frontmatter', 'not a skill\n'],
    ['foreign name', '---\nname: other-skill\n---\nbody\n'],
    ['missing ownership marker', '---\nname: mind-management\n---\n\n<!-- not ours -->\n'],
  ])('fails when the current skill has %s', async (_label, skill) => {
    const harness = makeCurrentHarness({ skill, activation: ACTIVATION_CONTENT });
    await expectContamination(verifyCurrent(harness, goodResolver(harness.dir)), 'skill');
    rmSync(harness.root, { recursive: true, force: true });
  });

  test.each([
    ['missing mind-management', 'Call system_instructions when needed.\n'],
    ['missing system_instructions', 'Load the mind-management skill.\n'],
    ['full protocol body', 'mind-management system_instructions\n## ORIENT\nfull body\n'],
    ['oversized activation', `mind-management system_instructions\n${'x'.repeat(2_000)}`],
  ])('fails when the current activation has %s', async (_label, activation) => {
    const harness = makeCurrentHarness({ skill: SKILL_CONTENT, activation });
    await expectContamination(verifyCurrent(harness, goodResolver(harness.dir)), 'activation');
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails when the inline config lists the activation twice', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    harness.env.OPENCODE_CONFIG_CONTENT = JSON.stringify({
      instructions: [harness.activationPath, harness.activationPath],
    });
    await expectContamination(verifyCurrent(harness, goodResolver(harness.dir)), 'exactly once');
    rmSync(harness.root, { recursive: true, force: true });
  });

  test('fails when an extra skill appears in the current surface', async () => {
    const harness = makeCurrentHarness({
      skill: SKILL_CONTENT,
      activation: ACTIVATION_CONTENT,
    });
    await expectContamination(
      verifyCurrent(
        harness,
        goodResolver(harness.dir, {
          skills:
            '{"data":[{"id":"opencode"},{"id":"report"},{"id":"mind-management"},{"id":"user-private"}]}',
        })
      ),
      'skills'
    );
    rmSync(harness.root, { recursive: true, force: true });
  });

  test.each(['mind-v9', 'mind-v10', 'no-memory'] as const)(
    'rejects mind-management discovery under %s',
    async condition => {
      const resolver =
        condition === 'no-memory'
          ? cleanNoMemoryResolver(
              '{"data":[{"id":"opencode"},{"id":"report"},{"id":"mind-management"}]}'
            )
          : goodResolver(dir, {
              skills: '{"data":[{"id":"opencode"},{"id":"report"},{"id":"mind-management"}]}',
            });
      await expectContamination(verify(resolver, { condition }), 'skills');
    }
  );

  test.each(['mind-v9', 'mind-v10', 'no-memory'] as const)(
    'rejects an installed activation file under %s',
    async condition => {
      const historicalDir = isolationDirs(
        mkdtempSync(join(tmpdir(), `bench-verify-${condition}-`))
      );
      writeFile(briefActivationPath(historicalDir.home), ACTIVATION_CONTENT);
      const historicalEnv = { HOME: historicalDir.home, XDG_CONFIG_HOME: historicalDir.config };
      const resolver =
        condition === 'no-memory'
          ? (inv: CommandInvocation) => {
              const key = inv.args.join(' ');
              if (key === 'debug paths') return { stdout: `home ${historicalDir.home}\n` };
              if (key === 'debug config')
                return {
                  stdout: JSON.stringify([
                    {
                      type: 'document',
                      info: {
                        model: { providerID: 'openrouter', model: 'openai/gpt-6-luna' },
                      },
                    },
                  ]),
                };
              if (key === 'mcp list') return { stdout: 'No MCP servers configured\n' };
              return { stdout: condition === 'no-memory' ? '{"data":[]}' : '[]' };
            }
          : goodResolver(historicalDir, { skills: '{"data":[{"id":"opencode"}]}' });
      await expectContamination(
        verify(resolver, { condition, dir: historicalDir, env: historicalEnv }),
        'activation'
      );
    }
  );

  test.each(['mind-v9', 'mind-v10', 'no-memory'] as const)(
    'rejects an inline activation instruction under %s',
    async condition => {
      const historicalDir = isolationDirs(
        mkdtempSync(join(tmpdir(), `bench-verify-inline-${condition}-`))
      );
      const historicalEnv = {
        HOME: historicalDir.home,
        XDG_CONFIG_HOME: historicalDir.config,
        OPENCODE_CONFIG_CONTENT: JSON.stringify({
          instructions: [briefActivationPath(historicalDir.home)],
        }),
      };
      const resolver =
        condition === 'no-memory'
          ? (inv: CommandInvocation) => {
              const key = inv.args.join(' ');
              if (key === 'debug paths') return { stdout: `home ${historicalDir.home}\n` };
              if (key === 'debug config')
                return {
                  stdout: JSON.stringify([
                    {
                      type: 'document',
                      info: {
                        model: { providerID: 'openrouter', model: 'openai/gpt-6-luna' },
                      },
                    },
                  ]),
                };
              if (key === 'mcp list') return { stdout: 'No MCP servers configured\n' };
              return { stdout: condition === 'no-memory' ? '{"data":[]}' : '[]' };
            }
          : goodResolver(historicalDir, { skills: '{"data":[{"id":"opencode"}]}' });
      await expectContamination(
        verify(resolver, { condition, dir: historicalDir, env: historicalEnv }),
        'activation'
      );
    }
  );
});
