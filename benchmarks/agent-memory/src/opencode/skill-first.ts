// Shared skill-first preparation for current-checkout benchmark environments.
//
// The benchmark reproduces the product's regular OpenCode integration by
// running the real `<checkout>/mind setup opencode` once per isolated
// environment. Setup can exit 0 while skipping the skill, so the installed
// artifacts are validated before any session or prompt starts.

import { existsSync, lstatSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { isAbsolute, join, relative, resolve } from 'node:path';

import { BUILTIN_SKILLS } from '../config';
import type { CommandRunner } from '../exec';
import type { IsolationDirs } from '../isolation/opencode';

export const MIND_MANAGEMENT_SKILL = 'mind-management';

/** Exact skills a skill-first current environment may expose. */
export const SKILL_FIRST_SKILLS: readonly string[] = Object.freeze([
  ...BUILTIN_SKILLS,
  MIND_MANAGEMENT_SKILL,
]);

// Mirrors `SKILL_OWNERSHIP_MARKER` in `src/setup/skill-installation.ts`; the
// benchmark stays independent of product internals.
const SKILL_OWNERSHIP_MARKER = '<!-- mind-managed-skill: generated by mind setup; do not edit -->';

const SKILL_FRONTMATTER_NAME = /^name:\s*mind-management\s*$/m;
const MAX_BRIEF_ACTIVATION_LENGTH = 2_000;
const DEFAULT_SETUP_TIMEOUT_MS = 120_000;
const STDERR_TAIL_LENGTH = 2_000;

export type SkillFirstErrorCode =
  | 'invalid-environment'
  | 'missing-mind-bin'
  | 'missing-path'
  | 'setup-failed'
  | 'missing-skill'
  | 'invalid-skill'
  | 'missing-activation'
  | 'ambiguous-activation'
  | 'invalid-activation'
  | 'invalid-config';

export class SkillFirstSetupError extends Error {
  constructor(
    message: string,
    public readonly code: SkillFirstErrorCode,
    public readonly stderrTail = ''
  ) {
    super(message);
    this.name = 'SkillFirstSetupError';
  }
}

export interface PrepareSkillFirstInput {
  readonly dir: IsolationDirs;
  /** Session environment to prepare; its inline config receives the L2 path. */
  readonly env: Record<string, string>;
  readonly mindBin: string | null;
  readonly run: CommandRunner;
  readonly timeoutMs?: number;
}

export interface SkillFirstPreparation {
  readonly env: Record<string, string>;
  readonly skillPath: string;
  readonly activationPath: string;
}

/** Canonical `mind-management` skill file installed by the product. */
export function canonicalSkillPath(home: string): string {
  return join(home, '.agents', 'skills', 'mind-management', 'SKILL.md');
}

/** Brief L2 activation the product writes under the HOME config directory. */
export function briefActivationPath(home: string): string {
  return join(home, '.config', 'opencode', 'instructions', 'mind-memory-protocol.md');
}

function xdgBriefActivationPath(configHome: string): string {
  return join(configHome, 'opencode', 'instructions', 'mind-memory-protocol.md');
}

function isContained(parent: string, child: string): boolean {
  const rel = relative(resolve(parent), resolve(child));
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
}

function assertIsolatedEnvironment(dir: IsolationDirs): void {
  const roots = [dir.home, dir.config, dir.data, dir.state, dir.cache];
  for (const root of roots) {
    if (!isContained(dir.conditionDir, root)) {
      throw new SkillFirstSetupError(
        `isolated path '${root}' is outside the condition root '${dir.conditionDir}'`,
        'invalid-environment'
      );
    }
  }

  const realHome = resolve(process.env.HOME ?? homedir());
  if (resolve(dir.home) === realHome) {
    throw new SkillFirstSetupError(
      `isolated HOME must not be the real HOME '${realHome}'`,
      'invalid-environment'
    );
  }
}

/** Minimal child environment: no host env is spread implicitly. */
function buildSetupEnv(dir: IsolationDirs): Record<string, string> {
  const path = process.env.PATH;
  if (!path) {
    throw new SkillFirstSetupError('PATH is required to run mind setup opencode', 'missing-path');
  }

  return {
    PATH: path,
    HOME: dir.home,
    XDG_CONFIG_HOME: dir.config,
    XDG_DATA_HOME: dir.data,
    XDG_STATE_HOME: dir.state,
    XDG_CACHE_HOME: dir.cache,
    MIND_DB_PATH: dir.mindDb,
    MIND_DATA_DIR: dir.mindDataDir,
    MIND_SYNC_ROOT: dir.syncRoot,
    MIND_RAG: 'false',
  };
}

function validateSkill(skillPath: string): void {
  let stat: ReturnType<typeof lstatSync>;
  try {
    stat = lstatSync(skillPath);
  } catch {
    throw new SkillFirstSetupError(
      `canonical mind-management skill is missing at '${skillPath}'`,
      'missing-skill'
    );
  }

  if (!stat.isFile()) {
    throw new SkillFirstSetupError(
      `canonical mind-management skill is not a regular file at '${skillPath}'`,
      'invalid-skill'
    );
  }

  const content = readFileSync(skillPath, 'utf8');
  const frontmatterEnd = content.startsWith('---\n') ? content.indexOf('\n---', 4) : -1;
  const frontmatter = frontmatterEnd === -1 ? '' : content.slice(4, frontmatterEnd);

  if (!SKILL_FRONTMATTER_NAME.test(frontmatter)) {
    throw new SkillFirstSetupError(
      `canonical skill at '${skillPath}' has no 'name: mind-management' frontmatter`,
      'invalid-skill'
    );
  }
  if (!content.includes(SKILL_OWNERSHIP_MARKER)) {
    throw new SkillFirstSetupError(
      `canonical skill at '${skillPath}' has no ownership marker`,
      'invalid-skill'
    );
  }
}

function resolveActivationPath(dir: IsolationDirs): string {
  const candidates = [briefActivationPath(dir.home), xdgBriefActivationPath(dir.config)].filter(
    candidate => existsSync(candidate)
  );

  if (candidates.length === 0) {
    throw new SkillFirstSetupError(
      `brief activation is missing under '${briefActivationPath(dir.home)}' ` +
        `and '${xdgBriefActivationPath(dir.config)}'`,
      'missing-activation'
    );
  }
  if (candidates.length > 1) {
    throw new SkillFirstSetupError(
      `ambiguous brief activation: found '${candidates.join("' and '")}'`,
      'ambiguous-activation'
    );
  }
  return candidates[0]!;
}

function validateActivation(activationPath: string): void {
  const content = readFileSync(activationPath, 'utf8');

  if (!content.includes(MIND_MANAGEMENT_SKILL)) {
    throw new SkillFirstSetupError(
      `brief activation at '${activationPath}' does not mention ${MIND_MANAGEMENT_SKILL}`,
      'invalid-activation'
    );
  }
  if (!content.includes('system_instructions')) {
    throw new SkillFirstSetupError(
      `brief activation at '${activationPath}' does not mention system_instructions`,
      'invalid-activation'
    );
  }
  if (content.includes('## ORIENT')) {
    throw new SkillFirstSetupError(
      `brief activation at '${activationPath}' contains the full protocol body`,
      'invalid-activation'
    );
  }
  if (content.length >= MAX_BRIEF_ACTIVATION_LENGTH) {
    throw new SkillFirstSetupError(
      `brief activation at '${activationPath}' is ${content.length} chars ` +
        `(limit ${MAX_BRIEF_ACTIVATION_LENGTH - 1})`,
      'invalid-activation'
    );
  }
}

/**
 * Add the brief activation path to the first position of the inline
 * `OPENCODE_CONFIG_CONTENT.instructions` list exactly once.
 */
export function applyActivationToEnv(
  env: Record<string, string>,
  activationPath: string
): Record<string, string> {
  const content = env.OPENCODE_CONFIG_CONTENT;
  if (!content) {
    throw new SkillFirstSetupError(
      'OPENCODE_CONFIG_CONTENT is required to inject the brief activation',
      'invalid-config'
    );
  }

  let parsed: Record<string, unknown>;
  try {
    parsed = JSON.parse(content) as Record<string, unknown>;
  } catch {
    throw new SkillFirstSetupError('OPENCODE_CONFIG_CONTENT is not valid JSON', 'invalid-config');
  }

  const existing = Array.isArray(parsed.instructions)
    ? parsed.instructions.filter((entry): entry is string => typeof entry === 'string')
    : [];
  const deduped = [...new Set(existing)].filter(entry => entry !== activationPath);

  return {
    ...env,
    OPENCODE_CONFIG_CONTENT: `${JSON.stringify(
      { ...parsed, instructions: [activationPath, ...deduped] },
      null,
      2
    )}\n`,
  };
}

/**
 * Run the real installer once and validate its on-disk artifacts.
 *
 * The returned environment is ready for the isolated OpenCode sessions: it
 * carries the inline L2 activation path and the exact skill allowlist.
 */
export async function prepareSkillFirst(
  input: PrepareSkillFirstInput
): Promise<SkillFirstPreparation> {
  if (!input.mindBin) {
    throw new SkillFirstSetupError(
      'a mind binary path is required for skill-first setup',
      'missing-mind-bin'
    );
  }

  assertIsolatedEnvironment(input.dir);
  const childEnv = buildSetupEnv(input.dir);

  const result = await input.run({
    command: input.mindBin,
    args: ['setup', 'opencode'],
    cwd: input.dir.workspace,
    env: childEnv,
    timeoutMs: input.timeoutMs ?? DEFAULT_SETUP_TIMEOUT_MS,
  });

  if (result.exitCode !== 0) {
    const stderrTail = result.stderr.slice(-STDERR_TAIL_LENGTH).trim();
    throw new SkillFirstSetupError(
      `mind setup opencode exited ${result.exitCode}` + (stderrTail ? `: ${stderrTail}` : ''),
      'setup-failed',
      stderrTail
    );
  }

  const skillPath = canonicalSkillPath(input.dir.home);
  validateSkill(skillPath);

  const activationPath = resolveActivationPath(input.dir);
  validateActivation(activationPath);

  return {
    env: applyActivationToEnv(input.env, activationPath),
    skillPath,
    activationPath,
  };
}
